#Requires -RunAsAdministrator
<#
.SYNOPSIS
  Run tor as a Windows service so the onion services (e.g. SSH) come up at boot,
  without anyone logging in.

.DESCRIPTION
  - Copies tor.exe (+ geoip files) from Tor Browser into TorExpertBundle\tor\ of this repo
    (binaries are git-ignored). Re-run this script after a Tor Browser update to refresh it.
  - Writes TorExpertBundle\tor\torrc-service with absolute paths (git-ignored).
  - Gives the LOCAL SERVICE account access to Data\, the HiddenService dirs and the log.
  - Stops a manually started tor (the one started with "-f torrc"), installs/updates the
    "tor" service, sets it to start automatically and restart on failure, then waits for
    the SOCKS port and "Bootstrapped 100%".

  The existing HiddenServiceDir is reused, so the .onion address stays the same.
  Tor Browser keeps working: it runs its own tor on port 9150 with its own data folder.

  ! If you are connected over SSH *through this tor*, the session drops when the manual
    tor is stopped. Reconnect after ~30-60 s (the service brings the onion back).

.PARAMETER TorBrowserTor
  Folder that contains Tor Browser's tor.exe. Default: <repo>\..\Tor Browser\Browser\TorBrowser\Tor

.PARAMETER SshServiceDir
  Name of the HiddenServiceDir (under TorExpertBundle\tor\) that maps port 22. Default: TorHiddenService1

.PARAMETER Uninstall
  Stop and remove the service (files are left in place).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\scripts\install-tor-service.ps1
#>
[CmdletBinding()]
param(
  [string]$TorBrowserTor,
  [string]$SshServiceDir = 'TorHiddenService1',
  [int]$SocksPort = 9050,
  [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$Repo    = Split-Path -Parent $PSScriptRoot
$Bundle  = Join-Path $Repo 'TorExpertBundle'
$TorDir  = Join-Path $Bundle 'tor'
$DataDir = Join-Path $Bundle 'Data'
$Torrc   = Join-Path $TorDir 'torrc-service'
$LogFile = Join-Path $TorDir 'log.txt'
$TorExe  = Join-Path $TorDir 'tor.exe'
$HsDir   = Join-Path $TorDir $SshServiceDir
$Svc     = 'tor'
$LocalService = '*S-1-5-19'   # NT AUTHORITY\LOCAL SERVICE (SID, works on any Windows language)

function Step($m) { Write-Host "==> $m" -ForegroundColor Cyan }

if ($Uninstall) {
  Step "Removing service '$Svc'"
  if (Get-Service $Svc -ErrorAction SilentlyContinue) {
    Stop-Service $Svc -Force -ErrorAction SilentlyContinue
    & $TorExe --service remove
  } else { Write-Host "Service '$Svc' not installed." }
  return
}

if ($Repo -match '\s') {
  throw "The repo path contains a space ($Repo). tor's service command line doesn't quote paths; move the repo to a path without spaces."
}
if (-not $TorBrowserTor) { $TorBrowserTor = Join-Path (Split-Path -Parent $Repo) 'Tor Browser\Browser\TorBrowser\Tor' }
$SrcExe = Join-Path $TorBrowserTor 'tor.exe'
if (-not (Test-Path $SrcExe)) { throw "tor.exe not found in '$TorBrowserTor'. Pass -TorBrowserTor <folder>." }
if (-not (Test-Path $HsDir))  { Write-Warning "$HsDir does not exist yet - tor will create it with a NEW .onion address." }

# 1. stop the service (if any) and a manually started tor using our DataDirectory
if (Get-Service $Svc -ErrorAction SilentlyContinue) {
  Step "Stopping existing service '$Svc'"
  Stop-Service $Svc -Force -ErrorAction SilentlyContinue
}
$manual = Get-CimInstance Win32_Process -Filter "Name='tor.exe'" |
  Where-Object { $_.CommandLine -match '-f\s+"?torrc"?\s*$' }
foreach ($p in $manual) {
  Step "Stopping manually started tor (PID $($p.ProcessId))"
  Stop-Process -Id $p.ProcessId -Force
}
Start-Sleep -Seconds 2

# 2. copy binaries
Step "Copying tor.exe + geoip from Tor Browser"
New-Item -ItemType Directory -Force $TorDir, $DataDir | Out-Null
Copy-Item $SrcExe $TorExe -Force
foreach ($g in 'geoip', 'geoip6') {
  $src = Join-Path $TorBrowserTor $g
  if (Test-Path $src) { Copy-Item $src (Join-Path $TorDir $g) -Force }
}
& $TorExe --version | Select-Object -First 1

# 3. service torrc (absolute paths)
Step "Writing $Torrc"
@"
# Generated by scripts\install-tor-service.ps1 - edit here, then: Restart-Service tor
SocksPort 127.0.0.1:$SocksPort
DataDirectory $DataDir
GeoIPFile $(Join-Path $TorDir 'geoip')
GeoIPv6File $(Join-Path $TorDir 'geoip6')

# SSH onion service (existing keys -> same .onion address)
HiddenServiceDir $HsDir
HiddenServicePort 22 127.0.0.1:22

Log notice file $LogFile
"@ | Set-Content -Path $Torrc -Encoding ascii

& $TorExe --verify-config -f $Torrc | Select-Object -Last 2
if ($LASTEXITCODE -ne 0) { throw "torrc-service failed --verify-config" }

# 4. permissions for LOCAL SERVICE
Step "Granting LOCAL SERVICE access to Data, $SshServiceDir and the log"
New-Item -ItemType Directory -Force $HsDir | Out-Null
if (-not (Test-Path $LogFile)) { New-Item -ItemType File $LogFile | Out-Null }
icacls $DataDir /grant "${LocalService}:(OI)(CI)M" /T /Q | Out-Null
icacls $HsDir   /grant "${LocalService}:(OI)(CI)M" /T /Q | Out-Null
icacls $LogFile /grant "${LocalService}:M" /Q | Out-Null
icacls $TorDir  /grant "${LocalService}:(RX)" /Q | Out-Null

# 5. install / update service
if (Get-Service $Svc -ErrorAction SilentlyContinue) {
  Step "Re-installing service '$Svc' (picks up the new torrc path)"
  & $TorExe --service remove | Out-Null
  Start-Sleep -Seconds 2
}
Step "Installing service '$Svc'"
& $TorExe --service install -options -f $Torrc
Start-Sleep -Seconds 2
Stop-Service $Svc -Force -ErrorAction SilentlyContinue
# run as LOCAL SERVICE (least privilege); cmd /c because PowerShell 5.1 drops the empty password ""
cmd /c "sc.exe config $Svc obj= `"NT AUTHORITY\LocalService`" password= `"`" start= auto" | Out-Null
sc.exe failure $Svc reset= 86400 actions= restart/60000/restart/60000/restart/60000 | Out-Null
if (Test-Path $LogFile) { Move-Item $LogFile (Join-Path $TorDir 'log.prev.txt') -Force }
New-Item -ItemType File $LogFile -Force | Out-Null
icacls $LogFile /grant "${LocalService}:M" /Q | Out-Null
Start-Service $Svc

# 6. verify
Step "Waiting for SOCKS port $SocksPort and Bootstrapped 100%"
$ok = $false
for ($i = 0; $i -lt 90; $i++) {
  Start-Sleep -Seconds 2
  $listening = Get-NetTCPConnection -State Listen -LocalPort $SocksPort -ErrorAction SilentlyContinue
  $boot = Select-String -Path $LogFile -Pattern 'Bootstrapped 100%' -SimpleMatch -ErrorAction SilentlyContinue
  if ($listening -and $boot) { $ok = $true; break }
}
Get-Service $Svc | Format-Table Name, Status, StartType -AutoSize
(Get-CimInstance Win32_Service -Filter "Name='$Svc'") | Format-List StartName, PathName
if ($ok) {
  Write-Host "tor service is up. .onion for SSH:" -ForegroundColor Green
  Get-Content (Join-Path $HsDir 'hostname')
} else {
  Write-Warning "Not confirmed within 3 min. Check: Get-Content '$LogFile' -Tail 30"
}
